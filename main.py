NOBLE_GAS_CORES = {
    "[He]": "1s2",
    "[Ne]": "1s2 2s2 2p6",
    "[Ar]": "1s2 2s2 2p6 3s2 3p6",
    "[Kr]": "1s2 2s2 2p6 3s2 3p6 4s2 3d10 4p6",
    "[Xe]": "1s2 2s2 2p6 3s2 3p6 4s2 3d10 4p6 5s2 4d10 5p6",
    "[Rn]": "1s2 2s2 2p6 3s2 3p6 4s2 3d10 4p6 5s2 4d10 5p6 6s2 4f14 5d10 6p6",
}

def expand_core(config):
    out=config
    for core,exp in NOBLE_GAS_CORES.items():
        out=out.replace(core,exp)
    return out

def parse_config(config):
    result=[]
    for token in expand_core(config).split():
        m=re.match(r"^(\d)([spdf])(\d+)$", token)
        if m:
            n,orb,count=m.groups(); result.append((int(n),orb,int(count)))
    return result

def sup(n):
    return str(n).translate(str.maketrans("0123456789-+", "⁰¹²³⁴⁵⁶⁷⁸⁹⁻⁺"))

def pretty_compact(config):
    result=[]
    for token in config.split():
        if token in NOBLE_GAS_CORES:
            result.append(token); continue
        m=re.match(r"^(\d)([spdf])(\d+)$", token)
        if m:
            n,orb,c=m.groups(); result.append(f"{n}{orb}{sup(c)}")
        else: result.append(token)
    return " ".join(result)

