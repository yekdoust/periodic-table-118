        cats=['alkali metal','alkaline earth metal','transition metal','post-transition metal','metalloid','nonmetal','halogen','noble gas','lanthanide','actinide']
        for c in cats:
            card=LegendCard(CATEGORY_FA[c],COLORS[c]); legend.add_widget(card)
        legend.width=sum([dp(178) for _ in cats])
        legend_scroll.add_widget(legend); self.add_widget(legend_scroll)
        outer_y=ScrollView(do_scroll_x=False,bar_width=dp(4),size_hint=(1,1))
        horiz=ScrollView(do_scroll_y=False,bar_width=dp(4),size_hint=(1,None),height=dp(9*112+20))
        grid=GridLayout(cols=18,rows=9,spacing=dp(5),padding=dp(6),size_hint=(None,None),width=18*dp(97)+15*dp(5),height=9*dp(113)+15*dp(5))
        # Build 7 main periods + 2 f-block rows.
        lookup={(e['period'],e['group']):e for e in ELEMENTS.values() if e['period']<=7 and e['category'] not in ('lanthanide','actinide')}
        for row in range(1,8):
            for col in range(1,19):
                e=lookup.get((row,col))
                grid.add_widget(ElementCard(e) if e else Widget(size_hint=(None,None),size=(dp(92),dp(108))))
        f_lookup={(e['period'],e['group']):e for e in ELEMENTS.values() if e['category'] in ('lanthanide','actinide')}
        for row,period in [(8,6),(9,7)]:
            for col in range(1,19):
                e=f_lookup.get((period,col)) if 4<=col<=17 else None
                grid.add_widget(ElementCard(e) if e else Widget(size_hint=(None,None),size=(dp(92),dp(108))))
        horiz.add_widget(grid); outer_y.add_widget(horiz); self.add_widget(outer_y)
        self.add_widget(Label(text="برای جزئیات عنصر، روی خانه ضربه بزنید.",font_size=sp(13),color=SUBTEXT,size_hint=(1,None),height=dp(32)))

